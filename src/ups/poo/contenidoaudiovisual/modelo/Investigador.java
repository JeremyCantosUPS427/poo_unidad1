package ups.poo.contenidoaudiovisual.modelo;

public class Investigador {

    //VARIABLES
    
    private String nombre;
    
    //CONSTRUCTOR
    
    public Investigador(String nombre){
        this.nombre=nombre;
    }
    
    //SETTERS AND GETTERS

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}
